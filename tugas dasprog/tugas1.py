# TUGAS 1 CONTOH OPERATOR
# contoh operator penugasan
nilai = 10
nilai += 5
print(nilai)
# contoh operator logika
a = 7
print(a > 5 and a < 10)
# contoh operator bitwise
x = 2
y = 7
print(x & y)
# contoh operator identitas
a = [5,3,7]
b = [5,3,7]
c = [5,3,7]
print(a is b)
print(a is not c)
# contoh operator keanggotaan
minuman = ["teh", "kopi", "susu"]
print("matcha" in minuman)
print("matcha" not in minuman)